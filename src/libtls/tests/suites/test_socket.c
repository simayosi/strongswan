/**
 * Load one of the private keys for certificates issued during the test
 */
static private_key_t *load_key(chunk_t data)
{
	private_key_t *key;

	key = lib->creds->create(lib->creds, CRED_PRIVATE_KEY, KEY_ANY,
							 BUILD_BLOB, data, BUILD_END);
	ck_assert(key);
	return key;
}

/**
 * Issue a certificate for the given key, a self-signed CA certificate if no
 * issuer is given
 */
static certificate_t *issue_cert(char *subject, private_key_t *key,
								 certificate_t *ca, private_key_t *cakey)
{
	certificate_t *cert;
	public_key_t *pubkey;
	identification_t *id;

	pubkey = key->get_public_key(key);
	ck_assert(pubkey);
	id = identification_create_from_string(subject);
	cert = lib->creds->create(lib->creds, CRED_CERTIFICATE, CERT_X509,
							  BUILD_SIGNING_KEY, ca ? cakey : key,
							  BUILD_SIGNING_CERT, ca,
							  BUILD_PUBLIC_KEY, pubkey,
							  BUILD_SUBJECT, id,
							  BUILD_X509_FLAG, ca ? X509_NONE : X509_CA,
							  BUILD_END);
	ck_assert(cert);
	id->destroy(id);
	pubkey->destroy(pubkey);
	return cert;
}

/**
 * TLS test wrapper function for client certificates that are selected based
 * on the CAs in the server's CertificateRequest.
 *
 * The client uses an identity that is not contained in any certificate and
 * gets two RSA certificates, of which only the second can be verified by the
 * server. The server requests all trusted RSA CAs, so the RSA CA is requested
 * but the ECDSA CA is not.
 *
 * Without fallback, the first certificate is issued by the ECDSA CA, which is
 * unknown to the server, and the second by the RSA CA. The client has to use
 * the second certificate, which chains to the requested CA, even though the
 * first one also has a private key.
 *
 * With fallback, both certificates are issued by the ECDSA CA, which is
 * trusted but not requested, and there is no private key for the first. As
 * none of them chains to the requested CA, the client falls back to the second
 * certificate and has to send it along with a signature by its key.
 */
static void test_tls_ca_hint(tls_version_t version, uint16_t port,
							 bool fallback, u_int i)
{
	echo_server_config_t *client;
	private_key_t *rsa1, *rsa2, *rsa3, *ecdsa;
	certificate_t *rsa_ca, *ecdsa_ca, *first, *second;
	tls_cipher_suite_t *suites;
	char suite[128];
	int count;

	rsa1 = load_key(chunk_from_thing(ca_hint_rsa1));
	rsa2 = load_key(chunk_from_thing(ca_hint_rsa2));
	rsa3 = load_key(chunk_from_thing(ca_hint_rsa3));
	ecdsa = load_key(chunk_from_thing(ca_hint_ecdsa));

	rsa_ca = issue_cert("C=CH, O=strongSwan, CN=tls-ca-hint-rsa-ca",
						rsa1, NULL, NULL);
	ecdsa_ca = issue_cert("C=CH, O=strongSwan, CN=tls-ca-hint-ecdsa-ca",
						  ecdsa, NULL, NULL);
	first = issue_cert("C=CH, O=strongSwan, CN=tls-ca-hint-first",
					   rsa2, ecdsa_ca, ecdsa);
	if (fallback)
	{
		second = issue_cert("C=CH, O=strongSwan, CN=tls-ca-hint-second",
							rsa3, ecdsa_ca, ecdsa);
		creds->add_cert(creds, TRUE, ecdsa_ca);
		rsa2->destroy(rsa2);
	}
	else
	{
		second = issue_cert("C=CH, O=strongSwan, CN=tls-ca-hint-second",
							rsa3, rsa_ca, rsa1);
		ecdsa_ca->destroy(ecdsa_ca);
		creds->add_key(creds, rsa2);
	}
	creds->add_cert(creds, TRUE, rsa_ca);
	creds->add_key(creds, rsa3);
	rsa1->destroy(rsa1);
	ecdsa->destroy(ecdsa);

	server_config = create_config(version, port, TRUE);
	server_config->peer = "%any";
	client = create_config(version, port, TRUE);
	client->id = UNKNOWN_ID;
	client->local_auth = auth_cfg_create();
	client->local_auth->add(client->local_auth, AUTH_RULE_SUBJECT_CERT, first);
	client->local_auth->add(client->local_auth, AUTH_RULE_SUBJECT_CERT, second);

	start_echo_server(server_config);

	count = tls_crypto_get_supported_suites(TRUE, version, &suites);
	ck_assert(i < count);
	snprintf(suite, sizeof(suite), "%N", tls_cipher_suite_names, suites[i]);
	lib->settings->set_str(lib->settings, "%s.tls.suites", suite, lib->ns);

	run_echo_client(client);

	client->local_auth->destroy(client->local_auth);
	free(client);
	free(suites);
}

